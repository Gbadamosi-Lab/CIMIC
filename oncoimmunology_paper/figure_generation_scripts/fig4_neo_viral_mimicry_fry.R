# ---------------------------------------------------------------------------
# 7. Generate a single boxplot for the viral mimicry program (aggregated score)
# ---------------------------------------------------------------------------
program_score_z <- df_z %>%
  dplyr::rowwise() %>%
  dplyr::mutate(ProgramScore = mean(c_across(all_of(viral_genes_present)), na.rm = TRUE)) %>%
  dplyr::ungroup() %>%
  dplyr::select(CIMIC_Cluster, ProgramScore)

format_p_annotation <- function(p, prefix = "P") {
  if (is.na(p) || !is.finite(p)) {
    return(paste0(prefix, " = NA"))
  }
  if (p < 0.001) {
    return(paste0(prefix, " < 0.001"))
  }
  paste0(prefix, " = ", formatC(p, format = "f", digits = 3))
}

program_pvalue <- NA_real_

# ---------------------------------------------------------------------------
# 8. Create and save the program boxplot (after limma test is performed)
# ---------------------------------------------------------------------------
make_program_boxplot <- function() {
  prog_sig <- dplyr::case_when(
    program_pvalue <= 0.0001 ~ "****",
    program_pvalue <= 0.001  ~ "***",
    program_pvalue <= 0.01   ~ "**",
    program_pvalue <= 0.05   ~ "*",
    TRUE                     ~ ""
  )
  star_y <- max(program_score_z$ProgramScore, na.rm = TRUE) * 0.9
  p <- ggplot(program_score_z, aes(x = CIMIC_Cluster, y = ProgramScore, fill = CIMIC_Cluster)) +
    geom_boxplot(outlier.shape = NA, colour = "black", width = 0.6, alpha = 1) +
    geom_jitter(width = 0.15, size = 3, shape = 16, colour = "black", alpha = 1) +
    annotate("text", x = 1.5, y = star_y, label = prog_sig, size = 10, fontface = "bold") +
    scale_x_discrete(labels = c("1" = "Dys\nCIM", "2" = "Fun\nCIM"), expand = expansion(add = c(0.5, 0.5))) +
    scale_fill_manual(values = c("1" = "#F8766D", "2" = "#00BFC4")) +
    labs(title = "Viral Mimicry", x = NULL, y = "Z‑score of\nProgram Activation") +
    theme_classic(base_size = 18) +
    theme(
      axis.text.x = element_text(face = "bold", size = 24, colour = "black"),
      axis.text.y = element_text(face = "bold", size = 24, colour = "black"),
      axis.title.y = element_text(face = "bold", size = 24, colour = "black"),
      plot.title = element_text(face = "bold", size = 24, hjust = 0.5),
      legend.position = "none",
      panel.grid = element_blank(),
      panel.border = element_rect(linewidth = 1, fill = NA)
    )
  out_file <- "oncoimmunology_paper/Results/fig4_neo_viral_mimicry_program_boxplot.png"
  ggsave(out_file, plot = p, width = 6, height = 5, dpi = 300, bg = "white")
  message(sprintf("✓ Saved: %s", out_file))
}

# ---------------------------------------------------------------------------
# 7. Per‑gene limma moderated‑t test (Fun vs Dys)
# ---------------------------------------------------------------------------
expr_matrix <- clustered_plot_df %>%
  dplyr::select(sample_id, all_of(viral_genes_present)) %>%
  tibble::column_to_rownames("sample_id") %>%
  t() %>%
  as.matrix()
storage.mode(expr_matrix) <- "numeric"

cluster_factor <- factor(clustered_plot_df$CIMIC_Cluster, levels = c("2", "1"))
design <- model.matrix(~ 0 + cluster_factor)
colnames(design) <- c("Fun_CIM", "Dys_CIM")

contrast <- limma::makeContrasts(Dys_CIM - Fun_CIM, levels = design)

fit <- limma::lmFit(expr_matrix, design)
fit2 <- limma::contrasts.fit(fit, contrast)
fit2 <- limma::eBayes(fit2)

top_tab <- limma::topTable(fit2, number = Inf, sort.by = "none")
limma_stats <- data.frame(
  Gene = rownames(top_tab),
  logFC = top_tab$logFC,
  AveExpr = top_tab$AveExpr,
  t = top_tab$t,
  PValue = top_tab$P.Value,
  adj.P.Val = top_tab$adj.P.Val,
  stringsAsFactors = FALSE
)

# Compute a program‑level p‑value (aggregate across all viral mimicry genes)
program_expr <- colMeans(expr_matrix)
program_matrix <- matrix(program_expr, nrow = 1)
rownames(program_matrix) <- "ViralMimicry"

fit_prog <- limma::lmFit(program_matrix, design)
fit_prog2 <- limma::contrasts.fit(fit_prog, contrast)
fit_prog2 <- limma::eBayes(fit_prog2)
prog_top <- limma::topTable(fit_prog2, number = 1, sort.by = "none")
program_pvalue <- prog_top$P.Value

stats_path <- "oncoimmunology_paper/Results/neo_viral_mimicry_limma_stats.csv"
write.csv(limma_stats, file = stats_path, row.names = FALSE)
message("✓ Saved limma stats: ", stats_path)

add_heatmap_stars()


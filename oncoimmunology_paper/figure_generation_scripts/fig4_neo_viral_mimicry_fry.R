# ---------------------------------------------------------------------------
# 6b. Add significance stars to heatmap (based on limma p‑values)
# ---------------------------------------------------------------------------
add_heatmap_stars <- function() {
  sig_labels <- limma_stats %>%
    dplyr::mutate(
      signif_label = dplyr::case_when(
        PValue <= 0.0001 ~ "****",
        PValue <= 0.001  ~ "***",
        PValue <= 0.01   ~ "**",
        PValue <= 0.05   ~ "*",
        TRUE             ~ ""
      )
    ) %>%
    dplyr::select(Gene, signif_label)

  heatmap_df <<- heatmap_df %>%
    dplyr::left_join(sig_labels, by = "Gene") %>%
    dplyr::mutate(Gene = factor(Gene, levels = rev(sort(unique(Gene)))))

  star_df <- heatmap_df %>%
    dplyr::distinct(Gene, signif_label) %>%
    dplyr::mutate(y = seq_along(levels(heatmap_df$Gene)))

  p_heatmap <<- p_heatmap +
    ggplot2::annotate(
      "text",
      x = 2.55,
      y = star_df$y,
      label = rev(star_df$signif_label),
      size = 10,
      fontface = "bold",
      hjust = 0,
      colour = "black"
    )
}


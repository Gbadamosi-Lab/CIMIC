# ---------------------------------------------------------------------------
# 2. Load data
# ---------------------------------------------------------------------------
clustered_plot_df <- data.table::fread(
  "oncoimmunology_paper/Datasets/NEO/neo_clustered_plot_df.csv",
  data.table = FALSE
) %>% as.data.frame()

# Ensure cluster column is present and correctly named
if ("cluster_assignments" %in% colnames(clustered_plot_df)) {
  clustered_plot_df <- clustered_plot_df %>%
